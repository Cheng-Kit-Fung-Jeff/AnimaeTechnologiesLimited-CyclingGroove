    public static void Draw(Vector3 positionA, Vector3 positionB, Vector3 forward, float pathWidth, bool enterA, bool enterB)
    {
        Vector3 cross = Vector3.Cross((positionA - positionB).normalized, forward), widthCross = pathWidth * cross;
        float distance = Vector3.Distance(positionA, positionB), radius = 0.125f * distance;

        Gizmos.color = Color.magenta;
        Gizmos.DrawLine(positionA + widthCross, positionB + widthCross);
        Gizmos.DrawLine(positionA - widthCross, positionB - widthCross);

        Gizmos.color = Color.blue;
        Gizmos.DrawWireSphere(positionA, radius);
        Gizmos.DrawWireSphere(positionB, radius);
        Gizmos.color = Color.green;
        if (enterA)
        {
            Vector3 near = Vector3.Lerp(positionA, positionB, 0.33f),
                nearnear = Vector3.Lerp(positionA, positionB, 0.23f),
            shortCross = 0.1f * distance * cross;
            Gizmos.DrawLine(nearnear - shortCross, near);
            Gizmos.DrawLine(nearnear + shortCross, near);
        }
        if (enterB)
        {
            Vector3 near = Vector3.Lerp(positionA, positionB, 0.67f),
                nearnear = Vector3.Lerp(positionA, positionB, 0.77f),
            shortCross = 0.1f * distance * cross;
            Gizmos.DrawLine(nearnear - shortCross, near);
            Gizmos.DrawLine(nearnear + shortCross, near);
        }
    }
